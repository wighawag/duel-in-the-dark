/**
 * Writes crs/index.ts: the proving setup (CRS) every circuit here needs, so
 * that proving never downloads anything, in node or in the browser.
 *
 * WHY. Left to itself, bb.js fetches its CRS from Aztec's CDN when a prover
 * starts: 2^19 G1 points (16 MB) plus 4 MB of Grumpkin points in the browser,
 * whatever the circuit, and the native backend in node downloads into
 * ~/.bb-crs. A game served on a LAN with no internet then cannot prove at
 * all. UltraHonk only needs as many BN254 G1 points as the largest circuit's
 * (dyadic) size, plus the G2 point, and no Grumpkin points; that is a few
 * hundred KB at most, so they are committed and handed to the prover
 * (src/index.ts `createZK`).
 *
 * WHEN IT RUNS. `pnpm build` runs it before `generate` (which needs the
 * points to produce verification keys). It reads the compiled circuits in
 * target/ (or the committed ones in generated/), and only downloads when a
 * circuit has outgrown the committed points, or with `--force`. So it needs
 * the internet only when a circuit grows past the next power of two.
 *
 * TRUST. The points are the first ones of the same file bb.js downloads
 * (Aztec's ceremony output), decompressed by bb.js itself. The script checks
 * that the first point is the BN254 generator (1, 2) and records the SHA-256
 * of what it wrote; it cannot check more than bb.js would.
 */
import {existsSync, readFileSync, readdirSync, writeFileSync, mkdirSync} from 'node:fs';
import {join, dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
import {gunzipSync} from 'node:zlib';
import {createHash} from 'node:crypto';
import {Barretenberg, BackendType} from '@aztec/bb.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const crsDir = join(root, 'crs');
const crsFile = join(crsDir, 'index.ts');
const HOST = 'https://crs.aztec-cdn.foundation';
/** bb.js only takes compressed points in whole chunks of this many bytes. */
const CHUNK_BYTES = 4 * 1024 * 1024;
const COMPRESSED = 32;
const UNCOMPRESSED = 64;

function circuitFiles(): string[] {
	for (const dir of [join(root, 'target'), join(root, 'generated')]) {
		if (!existsSync(dir)) continue;
		const files = readdirSync(dir)
			.filter((f) => f.endsWith('.json'))
			.map((f) => join(dir, f));
		if (files.length > 0) return files;
	}
	throw new Error('no compiled circuit in target/ or generated/');
}

function committedPoints(): number {
	if (!existsSync(crsFile)) return 0;
	const m = /export const CRS_POINTS = (\d+);/.exec(readFileSync(crsFile, 'utf8'));
	return m ? Number(m[1]) : 0;
}

async function fetchBytes(path: string, range?: string): Promise<Uint8Array> {
	const response = await fetch(`${HOST}/${path}`, range ? {headers: {Range: range}} : {});
	if (!response.ok) throw new Error(`${path}: HTTP ${response.status}`);
	return new Uint8Array(await response.arrayBuffer());
}

const api = await Barretenberg.new({backend: BackendType.Wasm, threads: 1, skipSrsInit: true});
try {
	let needed = 0;
	for (const file of circuitFiles()) {
		const {bytecode} = JSON.parse(readFileSync(file, 'utf8')) as {bytecode: string};
		const [, dyadic] = await api.acirGetCircuitSizes(
			gunzipSync(Buffer.from(bytecode, 'base64')),
			true,
			false,
		);
		needed = Math.max(needed, dyadic);
	}
	const have = committedPoints();
	if (have >= needed && !process.argv.includes('--force')) {
		console.log(`crs: ${have} points committed, the largest circuit needs ${needed}`);
	} else {
		const chunks = Math.ceil((needed * COMPRESSED) / CHUNK_BYTES);
		const compressed = await fetchBytes('g1_compressed.dat', `bytes=0-${chunks * CHUNK_BYTES - 1}`);
		const g2 = await fetchBytes('g2.dat');
		const {pointsBuf} = await api.srsInitSrs({
			pointsBuf: compressed,
			numPoints: compressed.length / COMPRESSED,
			g2Point: g2,
		});
		const g1 = pointsBuf.slice(0, needed * UNCOMPRESSED);
		const generator = new Uint8Array(UNCOMPRESSED);
		generator[31] = 1;
		generator[63] = 2;
		if (
			g1.length !== needed * UNCOMPRESSED ||
			!g1.subarray(0, UNCOMPRESSED).every((b, i) => b === generator[i])
		)
			throw new Error('crs: the first G1 point is not the BN254 generator');
		const sha = (b: Uint8Array) => createHash('sha256').update(b).digest('hex');
		mkdirSync(crsDir, {recursive: true});
		writeFileSync(
			crsFile,
			`// GENERATED by scripts/crs.ts. Do not edit.
//
// The proving setup every circuit here needs: the first ${needed} BN254 G1
// points of Aztec's CRS (${HOST}/g1_compressed.dat), uncompressed
// (64 bytes a point), and its G2 point. Committed so that proving never
// downloads anything (see scripts/crs.ts).
//
// sha256(g1) ${sha(g1)}
// sha256(g2) ${sha(g2)}
export const CRS_POINTS = ${needed};
export const CRS_G1 = '${Buffer.from(g1).toString('base64')}';
export const CRS_G2 = '${Buffer.from(g2).toString('base64')}';
`,
		);
		console.log(`crs: wrote ${needed} points (${g1.length} bytes) to crs/index.ts`);
	}
} finally {
	await api.destroy();
}
