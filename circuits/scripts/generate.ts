/**
 * Run after `nargo compile --workspace`. For every compiled circuit it writes:
 *
 *   generated/<name>.json                       the artifact the prover executes
 *   generated/index.ts                          a typed map of all of them
 *   ../contracts/src/verifiers/<Name>Verifier.sol  its on-chain verifier
 *   ../contracts/src/verifiers/HonkVerifierBase.sol  what every verifier shares
 *
 * All of them are COMMITTED, so that the contracts compile and the web builds
 * on a machine without nargo. Only someone changing a circuit needs the
 * devshell.
 *
 * The verifier comes from the same bb.js that proves (see src/index.ts). bb
 * emits ONE file per circuit, but only its head is about the circuit: the
 * sizes, the VK hash and the verification key. Everything after it (the
 * transcript, the relations, the base verifier) is byte-identical for every
 * circuit, and its libraries are LINKED, i.e. deployed separately. So the file
 * is split: the shared part becomes HonkVerifierBase.sol, deployed once and
 * linked by every verifier, and each circuit keeps a small file with its key.
 * If two circuits ever produce different shared parts, generation fails rather
 * than silently picking one.
 */
import {readFileSync, readdirSync, writeFileSync, mkdirSync, rmSync, existsSync} from 'node:fs';
import {join, dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
import {createZK, type CompiledCircuit} from '../src/index.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const targetDir = join(root, 'target');
const generatedDir = join(root, 'generated');
const verifiersDir = join(root, '..', 'contracts', 'src', 'verifiers');

const names = readdirSync(targetDir)
	.filter((f) => f.endsWith('.json'))
	.map((f) => f.slice(0, -'.json'.length))
	.sort();
if (names.length === 0)
	throw new Error('no compiled circuit in target/: run `nargo compile --workspace` first');

rmSync(generatedDir, {recursive: true, force: true});
mkdirSync(generatedDir, {recursive: true});
if (existsSync(verifiersDir)) {
	for (const f of readdirSync(verifiersDir))
		if (f.endsWith('Verifier.sol')) rmSync(join(verifiersDir, f));
}
mkdirSync(verifiersDir, {recursive: true});

const zk = await createZK();
let base: string | undefined;
try {
	for (const name of names) {
		const raw = readFileSync(join(targetDir, `${name}.json`), 'utf8');
		const circuit = JSON.parse(raw) as CompiledCircuit;
		writeFileSync(join(generatedDir, `${name}.json`), raw);

		const contractName = `${pascal(name)}Verifier`;
		const split = splitVerifier(await zk.prover(circuit).solidityVerifier());
		if (base !== undefined && base !== split.base) {
			throw new Error(
				`circuit ${name} needs a different HonkVerifierBase than the circuits before it: ` +
					'the shared-base assumption no longer holds, see the header of scripts/generate.ts',
			);
		}
		base = split.base;

		const keyLibrary = `${pascal(name)}VerificationKey`;
		writeFileSync(
			join(verifiersDir, `${contractName}.sol`),
			[
				`// GENERATED by circuits/scripts/generate.ts from circuits/${name}. Do not edit.`,
				'// SPDX-License-Identifier: Apache-2.0',
				'// Copyright 2022 Aztec',
				'pragma solidity ^0.8.27;',
				'',
				'import {BaseZKHonkVerifier, Honk} from "./HonkVerifierBase.sol";',
				'',
				split.key.replace(/\blibrary HonkVerificationKey\b/, `library ${keyLibrary}`).trim(),
				'',
				`contract ${contractName} is BaseZKHonkVerifier(N, LOG_N, VK_HASH, NUMBER_OF_PUBLIC_INPUTS) {`,
				'    function loadVerificationKey() internal pure override returns (Honk.VerificationKey memory) {',
				`        return ${keyLibrary}.loadVerificationKey();`,
				'    }',
				'}',
				'',
			].join('\n'),
		);
		console.log(`${name} -> generated/${name}.json, contracts/src/verifiers/${contractName}.sol`);
	}
} finally {
	await zk.destroy();
}

writeFileSync(
	join(verifiersDir, 'HonkVerifierBase.sol'),
	[
		'// GENERATED by circuits/scripts/generate.ts: the part of a bb.js verifier that every circuit shares. Do not edit.',
		'// SPDX-License-Identifier: Apache-2.0',
		'// Copyright 2022 Aztec',
		base!.trim(),
		'',
	].join('\n'),
);

writeFileSync(
	join(generatedDir, 'index.ts'),
	[
		'// GENERATED by scripts/generate.ts. Do not edit.',
		"import type {CompiledCircuit} from '@noir-lang/noir_js';",
		...names.map((n) => `import ${n} from './${n}.json' with {type: 'json'};`),
		'',
		'export const circuits = {',
		...names.map((n) => `\t${n}: ${n} as CompiledCircuit,`),
		'} as const;',
		'',
		'export type CircuitName = keyof typeof circuits;',
		'',
	].join('\n'),
);

/**
 * bb.js emits, in order: a license header, `pragma`, the circuit's constants
 * and `library HonkVerificationKey`; then a second `pragma` that starts the
 * shared verifier; then `contract HonkVerifier`, which only wires the two.
 */
function splitVerifier(solidity: string): {key: string; base: string} {
	const firstPragma = solidity.indexOf('pragma solidity');
	const secondPragma = solidity.indexOf('\npragma solidity', firstPragma + 1);
	const contract = solidity.search(/^contract HonkVerifier\b/m);
	if (firstPragma < 0 || secondPragma < 0 || contract < 0 || !(secondPragma < contract)) {
		throw new Error(
			'bb.js changed the layout of its verifier: update splitVerifier in scripts/generate.ts',
		);
	}
	const key = solidity.slice(solidity.indexOf('\n', firstPragma) + 1, secondPragma);
	if (!/\blibrary HonkVerificationKey\b/.test(key) || !/\bVK_HASH\b/.test(key)) {
		throw new Error(
			'bb.js verifier head no longer holds the verification key: update splitVerifier',
		);
	}
	return {key, base: solidity.slice(secondPragma + 1, contract)};
}

function pascal(snake: string): string {
	return snake
		.split(/[_-]/)
		.map((part) => part.charAt(0).toUpperCase() + part.slice(1))
		.join('');
}
